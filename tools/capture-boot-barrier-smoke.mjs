import vm from 'node:vm';
import {CAPTURE_BOOT_SOURCE} from './deterministic-world-capture.mjs';
const values = new Map();
const sessionStorage = {getItem:k=>values.has(k)?values.get(k):null,setItem:(k,v)=>values.set(k,String(v))};
const makeDocument = () => vm.createContext({sessionStorage,Promise});
const first = makeDocument();
vm.runInContext(CAPTURE_BOOT_SOURCE, first);
const firstPending = vm.runInContext('__gaiusBeforeMain()', first);
if (typeof first.__gaiusReleaseBoot !== 'function') throw new Error('first gate missing');
let settled = false;
firstPending.then(() => { settled = true; });
await Promise.resolve();
if (settled) throw new Error('first document gate was not blocked');
const firstRelease = first.__gaiusReleaseBoot;
firstRelease();
await firstPending;
const second = makeDocument();
vm.runInContext(CAPTURE_BOOT_SOURCE, second);
if (typeof second.__gaiusReleaseBoot !== 'function') throw new Error('successor release hook missing');
if (second.__gaiusReleaseBoot === firstRelease) throw new Error('successor reused old release hook');
const secondPending = vm.runInContext('__gaiusBeforeMain()', second);
let secondSettled = false;
secondPending.then(() => { secondSettled = true; });
await Promise.resolve();
if (secondSettled) throw new Error('successor document gate was released by the predecessor');
second.__gaiusReleaseBoot();
await secondPending;
console.log(JSON.stringify({ok:true,firstBlockedUntilRelease:true,reloadSecondDocumentBlocked:true,successorHasFreshReleaseHook:true}));
