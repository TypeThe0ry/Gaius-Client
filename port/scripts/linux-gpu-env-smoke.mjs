import assert from "node:assert/strict";
import {linuxGpuPci, linuxGpuEnvironment, linuxGpuArguments, linuxGpuProcessEvidence} from "./linux-gpu-env.mjs";

const inherited = {__GLX_VENDOR_LIBRARY_NAME: "mesa", VK_DRIVER_FILES: "software.json", PATH: "/usr/bin"};
assert.equal(linuxGpuEnvironment(inherited, "linux").VK_DRIVER_FILES, undefined);
assert.equal(linuxGpuEnvironment(inherited, "darwin").VK_DRIVER_FILES, "software.json");
assert.equal(linuxGpuEnvironment({...inherited, GAIUS_LINUX_GPU_ENV: "0"}, "linux").VK_DRIVER_FILES, "software.json");
assert.equal(inherited.VK_DRIVER_FILES, "software.json");
for (const bus of ["23", "41", "81"]) {
  const env = {...inherited, GAIUS_CHROME_GPU_PCI: `${bus}:00.0`, GAIUS_CHROME_GPU_BACKEND: "vulkan",
    VK_ICD_FILENAMES: "old.json", MESA_VK_DEVICE_SELECT: "cpu", NODEVICE_SELECT: "1"};
  const result = linuxGpuEnvironment(env, "linux", () => true);
  assert.equal(linuxGpuPci(env, "linux"), `0000:${bus}:00.0`);
  assert.equal(result.DRI_PRIME, `pci-0000_${bus}_00_0!`);
  assert.equal(result.MESA_VK_DEVICE_SELECT_FORCE_DEFAULT_DEVICE, "1");
  assert.equal(result.VK_DRIVER_FILES, "/usr/share/vulkan/icd.d/nvidia_icd.json");
  assert.equal(result.VK_ICD_FILENAMES, undefined);
  assert.equal(result.MESA_VK_DEVICE_SELECT, undefined);
  assert.equal(result.NODEVICE_SELECT, undefined);
  assert.equal(result.VK_INSTANCE_LAYERS, "VK_LAYER_MESA_device_select");
  assert.throws(() => linuxGpuEnvironment(env, "linux", () => false), /GPU selection requires/);
  const args = linuxGpuArguments(["--headless=new", "--use-angle=gl-egl", "--enable-features=Other"], env, "linux");
  assert.ok(args.includes("--use-angle=vulkan"));
  assert.ok(!args.includes("--use-angle=gl-egl"));
  assert.ok(args.includes("--enable-features=Other,Vulkan"));
  assert.throws(() => linuxGpuArguments(["--disable-features=Vulkan"], env, "linux"), /conflicts/);
}
assert.deepEqual(linuxGpuArguments(["--use-angle=gl-egl"], {}, "linux"), ["--use-angle=gl-egl"]);
const zinkEnv = {GAIUS_CHROME_GPU_PCI: "23:00.0", GAIUS_CHROME_GPU_BACKEND: "zink"};
const zink = linuxGpuEnvironment(zinkEnv, "linux", () => true);
assert.equal(zink.DRI_PRIME, "pci-0000_23_00_0");
assert.equal(zink.GALLIUM_DRIVER, "zink");
assert.equal(zink.MESA_LOADER_DRIVER_OVERRIDE, "zink");
assert.equal(zink.__EGL_VENDOR_LIBRARY_FILENAMES, "/usr/share/glvnd/egl_vendor.d/50_mesa.json");
const defaultEnv = {GAIUS_CHROME_GPU_PCI: "23:00.0"};
const defaultGpu = linuxGpuEnvironment(defaultEnv, "linux", () => true);
assert.equal(defaultGpu.GAIUS_CHROME_GPU_BACKEND, "zink-gl");
assert.equal(defaultGpu.DRI_PRIME, "pci-0000_23_00_0");
assert.equal(defaultGpu.GALLIUM_DRIVER, "zink");
const defaultArgs = linuxGpuArguments(["--use-angle=gl-egl", "--disable-features=Other"], defaultEnv, "linux");
assert.ok(defaultArgs.includes("--use-angle=gl-egl"));
assert.ok(!defaultArgs.includes("--use-vulkan=none"));
assert.ok(defaultArgs.includes("--enable-unsafe-webgpu"));
assert.ok(!defaultArgs.includes("--disable-gpu-compositing"));
assert.throws(() => linuxGpuArguments(["--enable-features=Vulkan"], defaultEnv, "linux"), /conflicts/);
assert.throws(() => linuxGpuArguments(["--disable-gpu-compositing"], defaultEnv, "linux"), /conflicts/);
const zinkArgs = linuxGpuArguments(["--use-angle=vulkan"], zinkEnv, "linux");
assert.ok(zinkArgs.includes("--use-angle=gl-egl"));
assert.ok(zinkArgs.includes("--disable-gpu-compositing"));
assert.ok(!zinkArgs.includes("--use-angle=vulkan"));
assert.throws(() => linuxGpuArguments(["--enable-features=Vulkan"], zinkEnv, "linux"), /conflicts/);
const zinkGlEnv = {...zinkEnv, GAIUS_CHROME_GPU_BACKEND: "zink-gl"};
assert.equal(linuxGpuEnvironment(zinkGlEnv, "linux", () => true).GALLIUM_DRIVER, "zink");
assert.deepEqual(defaultGpu, linuxGpuEnvironment(zinkGlEnv, "linux", () => true));
assert.deepEqual(defaultArgs, linuxGpuArguments(["--use-angle=gl-egl", "--disable-features=Other"], zinkGlEnv, "linux"));
assert.ok(!linuxGpuArguments([], zinkGlEnv, "linux").includes("--disable-gpu-compositing"));
assert.throws(() => linuxGpuArguments(["--disable-gpu-compositing"], zinkGlEnv, "linux"), /conflicts/);
const angleEnv = {...defaultEnv, GAIUS_CHROME_GPU_BACKEND: "angle-vulkan-gl"};
assert.equal(linuxGpuEnvironment(angleEnv, "linux", () => true).DRI_PRIME, "pci-0000_23_00_0!");
const angleArgs = linuxGpuArguments(["--use-angle=gl-egl", "--disable-features=Other"], angleEnv, "linux");
assert.ok(angleArgs.includes("--use-angle=vulkan"));
assert.ok(angleArgs.includes("--use-vulkan=none"));
assert.ok(angleArgs.includes("--disable-features=Other,Vulkan"));
assert.throws(() => linuxGpuArguments(["--enable-features=Vulkan"], angleEnv, "linux"), /requires/);
assert.throws(() => linuxGpuEnvironment({...zinkEnv, GAIUS_CHROME_GPU_BACKEND: "bad"}, "linux", () => true), /must be/);
assert.throws(() => linuxGpuPci({GAIUS_CHROME_GPU_PCI: "not-pci"}, "linux"), /PCI address/);
assert.throws(() => linuxGpuPci({GAIUS_CHROME_GPU_PCI: "23:00.0", GAIUS_LINUX_GPU_ENV: "0"}, "linux"), /requires/);
const xml = '<gpu id="00000000:23:00.0"><process_info><pid>42</pid></process_info></gpu>';
assert.equal(linuxGpuProcessEvidence(xml, [42], "0000:23:00.0").ok, true);
assert.equal(linuxGpuProcessEvidence(xml, [42], "0000:41:00.0").ok, false);
assert.equal(linuxGpuProcessEvidence(xml, [43], "0000:23:00.0").ok, false);
assert.equal(linuxGpuProcessEvidence(xml, [], "0000:23:00.0").ok, false);
const input = {__GLX_VENDOR_LIBRARY_NAME: "mesa", __EGL_VENDOR_LIBRARY_FILENAMES: "/usr/share/glvnd/egl_vendor.d/50_mesa.json", VK_DRIVER_FILES: "/usr/share/vulkan/icd.d/lvp_icd.json", PATH: "/usr/bin"};
const linux = linuxGpuEnvironment(input, "linux");
assert.equal(linux.__GLX_VENDOR_LIBRARY_NAME, undefined);
assert.equal(linux.VK_DRIVER_FILES, undefined);
assert.equal(linux.__EGL_VENDOR_LIBRARY_FILENAMES, "/usr/share/glvnd/egl_vendor.d/10_nvidia.json");
assert.equal(linux.PATH, "/usr/bin");
assert.equal(linuxGpuEnvironment(input, "darwin").__GLX_VENDOR_LIBRARY_NAME, "mesa");
assert.equal(linuxGpuEnvironment({...input, GAIUS_LINUX_GPU_ENV: "0"}, "linux").__GLX_VENDOR_LIBRARY_NAME, "mesa");
console.log("linux-gpu-env smoke: ok");
