package dev.gaius.tools;

import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.jar.JarEntry;
import java.util.jar.JarFile;
import org.objectweb.asm.ClassReader;
import org.objectweb.asm.ClassWriter;
import org.objectweb.asm.Opcodes;
import org.objectweb.asm.tree.AbstractInsnNode;
import org.objectweb.asm.tree.ClassNode;
import org.objectweb.asm.tree.FieldInsnNode;
import org.objectweb.asm.tree.InsnList;
import org.objectweb.asm.tree.MethodInsnNode;
import org.objectweb.asm.tree.MethodNode;
import org.objectweb.asm.tree.VarInsnNode;

/**
 * Adds opt-in first-successful-draw telemetry to the supported client profiles.
 *
 * <p>Section registration: 1.21.11 and 26.2 register in {@code LevelRenderer.prepareChunkRenders};
 * 26.3 moved the per-section loop into {@code extractSectionDrawGroups}. Draw commit: 1.21.11 and
 * 26.2 commit after {@code GlCommandEncoder.drawFromBuffers} in {@code executeDrawMultiple};
 * 26.3 removed both, and terrain draws go through the renderpearl frontend
 * {@code FrontendRenderPass.drawMultipleIndexed}, committed after its
 * {@code RenderPassBackend.drawIndexed} interface call.
 */
public final class MinecraftChunkDrawTelemetryPatcher {
    private static final String LEVEL_RENDERER =
            "net/minecraft/client/renderer/LevelRenderer.class";
    private static final String TELEMETRY_OWNER =
            "dev/gaius/browser/BrowserChunkDrawTelemetry";

    private MinecraftChunkDrawTelemetryPatcher() {
    }

    public static void main(String[] args) throws Exception {
        if (args.length != 3) {
            throw new IllegalArgumentException(
                    "usage: <profile id> <input.jar> <output-root>");
        }
        ProfileShape shape = ProfileShape.forId(args[0]);
        Path outputRoot = Path.of(args[2]);
        try (JarFile jar = new JarFile(args[1], false)) {
            if (jar.getJarEntry(shape.forbiddenEntry) != null) {
                throw new IllegalStateException("profile " + args[0] + " expects a client without "
                        + shape.forbiddenEntry + "; wrong jar for this profile");
            }
            // Registration and commit only work as a pair: patch both before writing either.
            byte[] levelRenderer = patchLevelRenderer(readEntry(jar, LEVEL_RENDERER), shape);
            byte[] drawLoop = patchGlCommandEncoder(readEntry(jar, shape.drawEntry), shape);
            writeClass(outputRoot.resolve(LEVEL_RENDERER), levelRenderer);
            writeClass(outputRoot.resolve(shape.drawEntry), drawLoop);
        }
        System.out.println("CHUNK_DRAW_TELEMETRY_PATCH_OK profile=" + args[0]
                + " levelMappings=1 lambdaArms=1 drawBegins=1 drawCommits=1");
    }

    private static byte[] patchLevelRenderer(byte[] bytes, ProfileShape shape) {
        ClassNode node = readClass(bytes);
        MethodNode prepare = find(node, shape.prepareName, shape.prepareDescriptor);
        MethodNode lambda = find(node, shape.lambdaName, shape.lambdaDescriptor);

        InsnList begin = new InsnList();
        // The identity field is profile-specific.  1.21.11 stores the active
        // ClientLevel on LevelRenderer, while 26.2 moved that state to the
        // renderer's LevelRenderState.  Keep the read on LevelRenderer itself
        // so the generated bytecode never reaches across a private field in
        // GameRenderer; TeaVM then sees a valid field for both class shapes.
        begin.add(new VarInsnNode(Opcodes.ALOAD, 0));
        begin.add(new FieldInsnNode(
                Opcodes.GETFIELD,
                "net/minecraft/client/renderer/LevelRenderer",
                shape.identityFieldName,
                shape.identityFieldDescriptor));
        begin.add(new MethodInsnNode(
                Opcodes.INVOKESTATIC,
                TELEMETRY_OWNER,
                "beginPrepare",
                "(Ljava/lang/Object;)V",
                false));
        prepare.instructions.insert(begin);

        VarInsnNode uniformStore = null;
        for (AbstractInsnNode instruction : prepare.instructions.toArray()) {
            if (!(instruction instanceof VarInsnNode store)
                    || store.getOpcode() != Opcodes.ISTORE
                    || store.var != shape.uniformIndexLocal) {
                continue;
            }
            AbstractInsnNode previous = previousOpcode(store);
            if (previous instanceof MethodInsnNode call
                    && call.name.equals("size")
                    && call.desc.equals("()I")) {
                if (uniformStore != null) {
                    throw new IllegalStateException("multiple guarded uniform-index stores");
                }
                uniformStore = store;
            }
        }
        if (uniformStore == null) {
            throw new IllegalStateException("uniform-index List.size() -> ISTORE shape changed");
        }
        InsnList register = new InsnList();
        register.add(new VarInsnNode(Opcodes.ILOAD, shape.uniformIndexLocal));
        register.add(new VarInsnNode(Opcodes.ALOAD, shape.blockPosLocal));
        register.add(new MethodInsnNode(
                Opcodes.INVOKEVIRTUAL,
                "net/minecraft/core/BlockPos",
                "getX",
                "()I",
                false));
        register.add(new VarInsnNode(Opcodes.ALOAD, shape.blockPosLocal));
        register.add(new MethodInsnNode(
                Opcodes.INVOKEVIRTUAL,
                "net/minecraft/core/BlockPos",
                "getZ",
                "()I",
                false));
        register.add(new MethodInsnNode(
                Opcodes.INVOKESTATIC,
                TELEMETRY_OWNER,
                "registerSection",
                "(III)V",
                false));
        prepare.instructions.insert(uniformStore, register);

        AbstractInsnNode callbackReturn = null;
        for (AbstractInsnNode instruction : lambda.instructions.toArray()) {
            if (instruction.getOpcode() == Opcodes.RETURN) {
                if (callbackReturn != null) {
                    throw new IllegalStateException("multiple ChunkSection callback returns");
                }
                callbackReturn = instruction;
            }
        }
        if (callbackReturn == null) {
            throw new IllegalStateException("ChunkSection callback return was not found");
        }
        InsnList arm = new InsnList();
        arm.add(new VarInsnNode(Opcodes.ILOAD, 0));
        arm.add(new MethodInsnNode(
                Opcodes.INVOKESTATIC,
                TELEMETRY_OWNER,
                "armUniformIndex",
                "(I)V",
                false));
        lambda.instructions.insertBefore(callbackReturn, arm);
        return writeClass(node);
    }

    private static byte[] patchGlCommandEncoder(byte[] bytes, ProfileShape shape) {
        ClassNode node = readClass(bytes);
        MethodNode execute = find(node, shape.executeName, shape.executeDescriptor);
        MethodInsnNode callbackAccessor = null;
        MethodInsnNode callbackAccept = null;
        MethodInsnNode drawCall = null;
        for (AbstractInsnNode instruction : execute.instructions.toArray()) {
            if (!(instruction instanceof MethodInsnNode call)) {
                continue;
            }
            if (call.owner.equals(shape.drawOwner)
                    && call.name.equals("uniformUploaderConsumer")
                    && call.desc.equals("()Ljava/util/function/BiConsumer;")) {
                if (callbackAccessor != null) {
                    throw new IllegalStateException("multiple draw callback accessors");
                }
                callbackAccessor = call;
            } else if (call.owner.equals("java/util/function/BiConsumer")
                    && call.name.equals("accept")
                    && call.desc.equals("(Ljava/lang/Object;Ljava/lang/Object;)V")) {
                callbackAccept = call;
            } else if (call.getOpcode() == shape.drawOpcode
                    && call.owner.equals(shape.drawCallOwner)
                    && call.name.equals(shape.drawCallName)
                    && call.desc.equals(shape.drawDescriptor)) {
                if (drawCall != null) {
                    throw new IllegalStateException("multiple " + shape.drawCallName + " calls");
                }
                drawCall = call;
            }
        }
        if (callbackAccessor == null || callbackAccept == null || drawCall == null
                || !precedes(callbackAccept, drawCall)) {
            throw new IllegalStateException(shape.executeName + " callback -> "
                    + shape.drawCallName + " shape changed");
        }
        VarInsnNode drawLoad = findDrawLoad(callbackAccessor, shape.drawLocal);
        if (drawLoad == null) {
            throw new IllegalStateException(shape.executeName
                    + " no longer keeps the current draw in local " + shape.drawLocal);
        }

        // The renderpearl terrain chain may be re-entered while an earlier step has already
        // instrumented this class. Accept that stable shape and keep the patch idempotent.
        if (!hasTelemetryCall(drawLoad, callbackAccessor, "beginDraw", "()V")) {
            InsnList clear = new InsnList();
            clear.add(new MethodInsnNode(
                    Opcodes.INVOKESTATIC,
                    TELEMETRY_OWNER,
                    "beginDraw",
                    "()V",
                    false));
            execute.instructions.insertBefore(callbackAccessor, clear);
        }

        if (!hasCommitForDrawPath(drawCall, shape)) {
            InsnList commit = new InsnList();
            commit.add(new VarInsnNode(Opcodes.ALOAD, shape.drawLocal));
            commit.add(new MethodInsnNode(
                    Opcodes.INVOKEVIRTUAL,
                    shape.drawOwner,
                    "indexCount",
                    "()I",
                    false));
            commit.add(new MethodInsnNode(
                    Opcodes.INVOKESTATIC,
                    TELEMETRY_OWNER,
                    "commitSuccessfulDraw",
                    "(I)V",
                    false));
            execute.instructions.insert(drawCall, commit);
        }
        return writeClass(node);
    }

    /** Finds the current draw load while allowing only the known telemetry call between it and
     * the callback accessor. This covers both a vanilla first pass and an already instrumented
     * renderpearl method without accepting a different local or unrelated stack shape. */
    private static VarInsnNode findDrawLoad(AbstractInsnNode callbackAccessor, int drawLocal) {
        int steps = 0;
        for (AbstractInsnNode cursor = callbackAccessor.getPrevious();
                cursor != null && steps++ < 8;
                cursor = cursor.getPrevious()) {
            if (cursor instanceof VarInsnNode load
                    && load.getOpcode() == Opcodes.ALOAD
                    && load.var == drawLocal) {
                return load;
            }
            if (cursor instanceof MethodInsnNode call
                    && !(call.getOpcode() == Opcodes.INVOKESTATIC
                    && call.owner.equals(TELEMETRY_OWNER)
                    && call.name.equals("beginDraw")
                    && call.desc.equals("()V"))) {
                return null;
            }
        }
        return null;
    }

    private static boolean hasTelemetryCall(
            AbstractInsnNode first, AbstractInsnNode end, String name, String descriptor) {
        for (AbstractInsnNode cursor = first.getNext(); cursor != end; cursor = cursor.getNext()) {
            if (cursor instanceof MethodInsnNode call
                    && call.getOpcode() == Opcodes.INVOKESTATIC
                    && call.owner.equals(TELEMETRY_OWNER)
                    && call.name.equals(name)
                    && call.desc.equals(descriptor)) {
                return true;
            }
        }
        return false;
    }

    /**
     * A commit from another draw path in the same execute method must not make this path look
     * patched. The patch inserts exactly {@code ALOAD drawLocal; INVOKEVIRTUAL indexCount;
     * INVOKESTATIC commitSuccessfulDraw} immediately after the selected draw call, so match that
     * sequence in insertion order.
     */
    private static boolean hasCommitForDrawPath(AbstractInsnNode drawCall, ProfileShape shape) {
        AbstractInsnNode drawLoad = nextOpcode(drawCall);
        if (!(drawLoad instanceof VarInsnNode load)
                || load.getOpcode() != Opcodes.ALOAD
                || load.var != shape.drawLocal) {
            return false;
        }
        AbstractInsnNode indexCount = nextOpcode(drawLoad);
        if (!(indexCount instanceof MethodInsnNode indexCall)
                || indexCall.getOpcode() != Opcodes.INVOKEVIRTUAL
                || !indexCall.owner.equals(shape.drawOwner)
                || !indexCall.name.equals("indexCount")
                || !indexCall.desc.equals("()I")) {
            return false;
        }
        AbstractInsnNode commit = nextOpcode(indexCount);
        return commit instanceof MethodInsnNode commitCall
                && commitCall.getOpcode() == Opcodes.INVOKESTATIC
                && commitCall.owner.equals(TELEMETRY_OWNER)
                && commitCall.name.equals("commitSuccessfulDraw")
                && commitCall.desc.equals("(I)V");
    }

    private static boolean precedes(AbstractInsnNode first, AbstractInsnNode second) {
        for (AbstractInsnNode cursor = first; cursor != null; cursor = cursor.getNext()) {
            if (cursor == second) {
                return true;
            }
        }
        return false;
    }

    private static AbstractInsnNode previousOpcode(AbstractInsnNode instruction) {
        AbstractInsnNode previous = instruction.getPrevious();
        while (previous != null && previous.getOpcode() < 0) {
            previous = previous.getPrevious();
        }
        return previous;
    }

    private static AbstractInsnNode nextOpcode(AbstractInsnNode instruction) {
        AbstractInsnNode next = instruction.getNext();
        while (next != null && next.getOpcode() < 0) {
            next = next.getNext();
        }
        return next;
    }

    private static ClassNode readClass(byte[] bytes) {
        ClassNode node = new ClassNode();
        new ClassReader(bytes).accept(node, 0);
        return node;
    }

    private static byte[] writeClass(ClassNode node) {
        ClassWriter writer = new ClassWriter(ClassWriter.COMPUTE_MAXS);
        node.accept(writer);
        return writer.toByteArray();
    }

    private static MethodNode find(ClassNode node, String name, String descriptor) {
        return node.methods.stream()
                .filter(method -> method.name.equals(name) && method.desc.equals(descriptor))
                .findFirst()
                .orElseThrow(() -> new IllegalStateException(
                        node.name + "." + name + descriptor + " was not found"));
    }

    private static byte[] readEntry(JarFile jar, String name) throws IOException {
        JarEntry entry = jar.getJarEntry(name);
        if (entry == null) {
            throw new IOException("missing jar entry: " + name);
        }
        try (InputStream input = jar.getInputStream(entry)) {
            return input.readAllBytes();
        }
    }

    private static void writeClass(Path output, byte[] bytes) throws IOException {
        Files.createDirectories(output.toAbsolutePath().getParent());
        Files.write(output, bytes);
    }

    /**
     * @param prepareName        LevelRenderer method holding the per-section registration
     * @param drawEntry          class holding the per-draw loop (and output entry)
     * @param executeName        per-draw loop method
     * @param drawOpcode         opcode of the call that issues one draw
     * @param drawCallOwner      owner of the call that issues one draw
     * @param drawCallName       name of the call that issues one draw
     * @param drawOwner          the RenderPass$Draw record type
     * @param forbiddenEntry     a class the profile's jar must not have (wrong-jar guard)
     */
    private record ProfileShape(
            String prepareName,
            String prepareDescriptor,
            String lambdaName,
            String lambdaDescriptor,
            int blockPosLocal,
            int uniformIndexLocal,
            String drawEntry,
            String executeName,
            String executeDescriptor,
            int drawOpcode,
            String drawCallOwner,
            String drawCallName,
            String drawDescriptor,
            String drawOwner,
            int drawLocal,
            String identityFieldName,
            String identityFieldDescriptor,
            String forbiddenEntry) {
        private static final String GL_COMMAND_ENCODER = "com/mojang/blaze3d/opengl/GlCommandEncoder";
        private static final String BLAZE3D_DRAW = "com/mojang/blaze3d/systems/RenderPass$Draw";
        private static final String RENDERPEARL = "com/mojang/renderpearl/";

        /**
         * The shape of the profile's client, chosen by its version profile fields: the legacy
         * patch set, or the modern one with a blaze3d or a renderpearl render API.
         */
        private static ProfileShape forId(String id) {
            VersionProfile profile = VersionProfile.forId(id);
            String returnType =
                    "Lnet/minecraft/client/renderer/chunk/ChunkSectionsToRender;";
            String lambdaDescriptor =
                    "(I[Lcom/mojang/blaze3d/buffers/GpuBufferSlice;"
                            + "Lcom/mojang/blaze3d/systems/RenderPass$UniformUploader;)V";
            if (profile.legacyPatchSet()) {
                return new ProfileShape(
                        "prepareChunkRenders",
                        "(Lorg/joml/Matrix4fc;DDD)" + returnType,
                        "lambda$prepareChunkRenders$6",
                        lambdaDescriptor,
                        17,
                        20,
                        GL_COMMAND_ENCODER + ".class",
                        "executeDrawMultiple",
                        "(Lcom/mojang/blaze3d/opengl/GlRenderPass;Ljava/util/Collection;"
                                + "Lcom/mojang/blaze3d/buffers/GpuBuffer;"
                                + "Lcom/mojang/blaze3d/vertex/VertexFormat$IndexType;"
                                + "Ljava/util/Collection;Ljava/lang/Object;)V",
                        Opcodes.INVOKEVIRTUAL,
                        GL_COMMAND_ENCODER,
                        "drawFromBuffers",
                        "(Lcom/mojang/blaze3d/opengl/GlRenderPass;III"
                                + "Lcom/mojang/blaze3d/vertex/VertexFormat$IndexType;"
                                + "Lcom/mojang/blaze3d/opengl/GlRenderPipeline;I)V",
                        BLAZE3D_DRAW,
                        8,
                        "level",
                        "Lnet/minecraft/client/multiplayer/ClientLevel;",
                        RENDERPEARL + "api/device/GpuDevice.class");
            }
            if (profile.modernPatchSet() && !profile.renderpearl()) {
                return new ProfileShape(
                        "prepareChunkRenders",
                        "(Lorg/joml/Matrix4fc;)" + returnType,
                        "lambda$prepareChunkRenders$1",
                        lambdaDescriptor,
                        11,
                        14,
                        GL_COMMAND_ENCODER + ".class",
                        "executeDrawMultiple",
                        "(Lcom/mojang/blaze3d/opengl/GlRenderPass;Ljava/util/Collection;"
                                + "Lcom/mojang/blaze3d/buffers/GpuBuffer;"
                                + "Lcom/mojang/blaze3d/IndexType;Ljava/util/Collection;"
                                + "Ljava/lang/Object;)V",
                        Opcodes.INVOKEVIRTUAL,
                        GL_COMMAND_ENCODER,
                        "drawFromBuffers",
                        "(Lcom/mojang/blaze3d/opengl/GlRenderPass;III"
                                + "Lcom/mojang/blaze3d/IndexType;"
                                + "Lcom/mojang/blaze3d/opengl/GlRenderPipeline;II)V",
                        BLAZE3D_DRAW,
                        8,
                        "levelRenderState",
                        "Lnet/minecraft/client/renderer/state/level/LevelRenderState;",
                        RENDERPEARL + "api/device/GpuDevice.class");
            }
            if (profile.modernPatchSet() && profile.renderpearl()) {
                // Registration: extractSectionDrawGroups keeps the render origin (BlockPos) in
                // local 14 and stores sectionInfos.size() into local 15. Draw: the frontend
                // loop keeps the current RenderPass$Draw in local 9 and issues it through the
                // RenderPassBackend interface.
                return new ProfileShape(
                        "extractSectionDrawGroups",
                        "(ZLjava/util/List;Ljava/util/Map;)I",
                        "lambda$prepareChunkRenders$2",
                        "(I[L" + RENDERPEARL + "api/buffers/GpuBufferSlice;"
                                + "L" + RENDERPEARL + "api/commands/RenderPass$UniformUploader;)V",
                        14,
                        15,
                        RENDERPEARL + "frontend/FrontendRenderPass.class",
                        "drawMultipleIndexed",
                        "(Ljava/util/Collection;L" + RENDERPEARL + "api/buffers/GpuBuffer;"
                                + "L" + RENDERPEARL + "api/pipeline/IndexType;"
                                + "Ljava/util/Collection;Ljava/lang/Object;)V",
                        Opcodes.INVOKEINTERFACE,
                        RENDERPEARL + "backend/api/RenderPassBackend",
                        "drawIndexed",
                        "(IIIII)V",
                        RENDERPEARL + "api/commands/RenderPass$Draw",
                        9,
                        "levelRenderState",
                        "Lnet/minecraft/client/renderer/state/level/LevelRenderState;",
                        GL_COMMAND_ENCODER + ".class");
            }
            throw new IllegalArgumentException("unsupported profile: " + id);
        }
    }
}
