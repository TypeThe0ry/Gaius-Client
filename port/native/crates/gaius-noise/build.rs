//! Compiles the `kernelSemantics` of every version profile (`port/versions/*.json`) into the
//! semantics table of `src/semantics.rs`. The profile JSON is the only place that knows which
//! Minecraft version has which semantics and which wire code names them; this script checks
//! that every declaration is one the kernels implement and that codes and tuples correspond
//! one to one, and fails the build otherwise.

use std::collections::BTreeMap;
use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
struct Tuple {
    floor_mode: &'static str,
    synth: &'static str,
    density_graph: &'static str,
    ir_version: u16,
}

fn main() {
    let manifest = PathBuf::from(env::var_os("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let versions = manifest.join("../../../versions");
    println!("cargo:rerun-if-changed={}", versions.display());
    let mut files: Vec<PathBuf> = fs::read_dir(&versions)
        .unwrap_or_else(|e| panic!("cannot list {}: {e}", versions.display()))
        .map(|entry| entry.expect("version profile entry").path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "json"))
        .collect();
    files.sort();
    assert!(!files.is_empty(), "{} holds no version profile", versions.display());

    let mut by_code: BTreeMap<u8, (Tuple, String)> = BTreeMap::new();
    let mut by_tuple: BTreeMap<Tuple, (u8, String)> = BTreeMap::new();
    let mut profiles = Vec::new();
    for file in &files {
        println!("cargo:rerun-if-changed={}", file.display());
        let (id, code, tuple) = read_profile(file);
        if let Some((known, first)) = by_code.get(&code) {
            assert!(
                *known == tuple,
                "{}: kernelSemantics.code {code} already names other semantics in profile {first}",
                file.display()
            );
        }
        if let Some((known, first)) = by_tuple.get(&tuple) {
            assert!(
                *known == code,
                "{}: profile {first} declares the same kernelSemantics with code {known}, not {code}",
                file.display()
            );
        }
        by_code.entry(code).or_insert((tuple, id.clone()));
        by_tuple.entry(tuple).or_insert((code, id.clone()));
        profiles.push((id, code));
    }

    let mut out = String::from("// Generated by build.rs from port/versions/*.json.\n");
    out.push_str("pub(super) const SEMANTICS: &[Semantics] = &[\n");
    for (code, (t, _)) in &by_code {
        writeln!(
            out,
            "    Semantics {{ code: {code}, floor_mode: FloorMode::{}, synth: Synth::{}, \
             density_graph: DensityGraph::{}, ir_version: {} }},",
            t.floor_mode, t.synth, t.density_graph, t.ir_version
        )
        .unwrap();
    }
    out.push_str("];\npub(super) const PROFILES: &[(&str, u8)] = &[\n");
    for (id, code) in &profiles {
        writeln!(out, "    ({id:?}, {code}),").unwrap();
    }
    out.push_str("];\n");
    let target = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR")).join("semantics_table.rs");
    fs::write(&target, out).unwrap_or_else(|e| panic!("cannot write {}: {e}", target.display()));
}

fn read_profile(file: &Path) -> (String, u8, Tuple) {
    let text = fs::read_to_string(file).unwrap_or_else(|e| panic!("cannot read {}: {e}", file.display()));
    let profile: serde_json::Value =
        serde_json::from_str(&text).unwrap_or_else(|e| panic!("{} is not JSON: {e}", file.display()));
    let fail = |what: &str| -> ! { panic!("{}: {what}", file.display()) };
    let id = profile["id"]
        .as_str()
        .unwrap_or_else(|| fail("id must be a string"))
        .to_owned();
    let semantics = &profile["kernelSemantics"];
    if !semantics.is_object() {
        fail("kernelSemantics must be an object");
    }
    let code = semantics["code"]
        .as_u64()
        .and_then(|c| u8::try_from(c).ok())
        .unwrap_or_else(|| fail("kernelSemantics.code must be an integer 0..=255"));
    let pick = |key: &str, choices: &[(&str, &'static str)]| -> &'static str {
        let value = semantics[key].as_str().unwrap_or("");
        choices
            .iter()
            .find(|(name, _)| *name == value)
            .map(|(_, variant)| *variant)
            .unwrap_or_else(|| {
                let names: Vec<&str> = choices.iter().map(|(name, _)| *name).collect();
                fail(&format!(
                    "kernelSemantics.{key} {value:?} is not implemented by the kernels (known: {names:?})"
                ))
            })
    };
    let tuple = Tuple {
        floor_mode: pick(
            "floorMode",
            &[("cast-adjust", "CastAdjust"), ("math-floor", "MathFloor")],
        ),
        synth: pick("synth", &[("f64", "F64"), ("f32", "F32")]),
        density_graph: pick(
            "densityGraph",
            &[("router-f64", "Router64"), ("sampler-f32", "Sampler32")],
        ),
        ir_version: semantics["irVersion"]
            .as_u64()
            .and_then(|v| u16::try_from(v).ok())
            .filter(|&v| v > 0)
            .unwrap_or_else(|| fail("kernelSemantics.irVersion must be an integer 1..=65535")),
    };
    // The f64 router runs on synth64 noises and the f32 samplers on synth32 ones.
    if (tuple.synth == "F32") != (tuple.density_graph == "Sampler32") {
        fail("kernelSemantics: synth f32 goes with densityGraph sampler-f32, f64 with router-f64");
    }
    (id, code, tuple)
}
